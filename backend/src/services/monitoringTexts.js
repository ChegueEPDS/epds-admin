const diagnosticPatterns = [
  [/^Response exceeded (\d+) ms$/, (_, limit) => `A válaszidő meghaladta a(z) ${limit} ms-os határt.`],
  [/^TLS certificate expires in (\d+) days$/, (_, days) => `A TLS-tanúsítvány ${days} nap múlva lejár.`],
  [/^(\d+) redirects before final response$/, (_, count) => `${count} átirányítás történt a végső válasz előtt.`],
  [/^Request timed out after (\d+) ms$/, (_, limit) => `A kérés túllépte a(z) ${limit} ms-os időkorlátot.`]
];

function monitoringText(language, source) {
  if (language !== 'hu' || typeof source !== 'string') return source;
  if (Object.hasOwn(hungarian, source)) return hungarian[source];
  for (const [pattern, translate] of diagnosticPatterns) {
    const match = source.match(pattern);
    if (match) return translate(...match);
  }
  return source;
}

module.exports = { monitoringText };
